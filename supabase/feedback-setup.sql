create table if not exists public.portfolio_feedback (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  relationship text check (relationship is null or char_length(relationship) <= 120),
  message text not null check (char_length(btrim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.portfolio_feedback enable row level security;

grant usage on schema public to anon;
grant select, insert on public.portfolio_feedback to anon;
grant usage, select on sequence public.portfolio_feedback_id_seq to anon;

drop policy if exists "Public can read portfolio feedback" on public.portfolio_feedback;
create policy "Public can read portfolio feedback"
  on public.portfolio_feedback
  for select
  to anon
  using (true);

drop policy if exists "Public can publish portfolio feedback" on public.portfolio_feedback;
create policy "Public can publish portfolio feedback"
  on public.portfolio_feedback
  for insert
  to anon
  with check (true);
